import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const target = new URL('docs/research/web-api-transport.json', root);
const catalog = JSON.parse(readFileSync(new URL('docs/research/web-api-model-coverage.json', root)));
const postExceptions = {
  'admin.conversations.restrictAccess.addGroup': 'Mutation: retain JSON POST, listed among supported content types.',
  'admin.conversations.restrictAccess.removeGroup': 'Mutation: retain JSON POST, listed among supported content types.',
  'admin.emoji.add': 'Mutation: retain JSON POST.',
  'admin.emoji.addAlias': 'Mutation: retain JSON POST.',
  'admin.emoji.remove': 'Mutation: retain JSON POST.',
  'admin.emoji.rename': 'Mutation: retain JSON POST.',
  'admin.teams.settings.setDefaultChannels': 'Mutation: retain JSON POST.',
  'admin.teams.settings.setIcon': 'Mutation: retain JSON POST.',
  'auth.revoke': 'Credential mutation: retain JSON POST.',
  'conversations.declineSharedInvite': 'Mutation: retain JSON POST.',
  'files.remote.share': 'Mutation: retain JSON POST.',
  'users.deletePhoto': 'Mutation: retain JSON POST.',
  'admin.roles.listAssignments': 'Array filters: retain supported JSON POST to preserve typed arguments.',
  'team.externalTeams.list': 'Array filters: retain supported JSON POST to preserve typed arguments.',
};
const oauth = new Set(['oauth.access', 'oauth.v2.access', 'oauth.v2.exchange', 'openid.connect.token']);

// Network access is explicit; normal verification uses the committed snapshot.
if (process.argv.includes('--refresh')) {
  const pending = catalog.endpoints.map(({ method }) => method);
  const methods = {};
  await Promise.all(Array.from({ length: 6 }, async () => {
    while (pending.length) {
      const method = pending.shift();
      const source = `https://docs.slack.dev/reference/methods/${method}.md`;
      const response = await fetch(source, { signal: AbortSignal.timeout(30000) });
      if (!response.ok) throw new Error(`${method}: HTTP ${response.status}`);
      const document = await response.text();
      const verb = document.match(/^http_method: "(GET|POST)"$/m)?.[1];
      const name = document.match(/^method_name: "(.+)"$/m)?.[1];
      if (!verb || name !== method) throw new Error(`${method}: missing or mismatched contract`);
      const facts = document.split('**Content types**')[1]?.split('**Rate Limits**')[0] ?? '';
      const contentTypes = [...new Set(facts.match(/application\/[a-z+\-]+/g) ?? [])].sort();
      if (!contentTypes.length) throw new Error(`${method}: missing content types`);
      methods[method] = { verb, contentTypes, source, sha256: createHash('sha256').update(document).digest('hex') };
    }
  }));
  writeFileSync(target, `${JSON.stringify({ schema: 1, retrievedAt: new Date().toISOString().slice(0, 10), methods: Object.fromEntries(Object.entries(methods).sort()) }, null, 2)}\n`);
}

const snapshot = JSON.parse(readFileSync(target));
const expected = catalog.endpoints.map(({ method }) => method).sort();
if (JSON.stringify(Object.keys(snapshot.methods).sort()) !== JSON.stringify(expected)) {
  throw new Error('Transport snapshot and generated endpoint inventory differ. Refresh and review the contracts.');
}
const get = [];
const form = [];
for (const method of expected) {
  const contract = snapshot.methods[method];
  if (postExceptions[method]) {
    if (!contract.contentTypes.includes('application/json')) throw new Error(`${method}: exception no longer supports JSON`);
  } else if (contract.verb === 'GET') get.push(method);
  if (oauth.has(method) || !contract.contentTypes.includes('application/json')) form.push(method);
}
const php = `<?php

declare(strict_types=1);

namespace Thunder\\Bolt\\WebApi;

// Generated by scripts/audit-web-api-transport.mjs from reviewed Slack contracts.
// Exceptions and evidence live in that script and docs/research/web-api-transport.json.
final class MethodTransport
{
    public const array GET = [
${get.map((method) => `        '${method}',`).join('\n')}
    ];

    public const array FORM = [
${form.map((method) => `        '${method}',`).join('\n')}
    ];
}
`;
const phpTarget = new URL('src/WebApi/MethodTransport.php', root);
if (process.argv.includes('--verify')) {
  if (readFileSync(phpTarget, 'utf8') !== php) throw new Error('MethodTransport.php is stale. Run the transport audit script.');
} else writeFileSync(phpTarget, php);
console.log(`Verified transport evidence for ${expected.length} endpoints.`);
